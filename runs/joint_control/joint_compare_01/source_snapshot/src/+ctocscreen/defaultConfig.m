function c=defaultConfig(mode)
%DEFAULTCONFIG Search limits are approximations, not competition constraints.
if nargin<1, mode='batch'; end
c=struct('master_seed',20260921,'max_candidates',1000,'archive_size',16, ...
 'max_wall_s',3600,'display_interval',10,'checkpoint_interval',10, ...
 'run_id',string(datetime('now','Format','yyyyMMdd_HHmmss_SSS')), ...
 'flyby_limit_km',1,'min_altitude_km',200,'min_tof_s',60, ...
 'branch_policy',struct('max_revolutions',2,'endpoint_tol_km',1e-4), ...
 'construct_target_count',5,'construct_times_s',[900 1800 3600 7200 14400], ...
 'construction_min_altitude_after_first_km',6000,'export_audit_count',16, ...
 'restart_probability',0.15,'refine_every',25,'refine_evaluations',150, ...
 'refine_iterations',4,'workers',0,'tasks',8,'algorithm_version',2);
if strcmp(mode,'smoke')
 c.max_candidates=5; c.max_wall_s=120; c.tasks=2;
 c.display_interval=1; c.refine_every=0;
elseif strcmp(mode,'pilot')
 c.max_candidates=40; c.max_wall_s=180; c.tasks=2; c.refine_every=10;
elseif ~strcmp(mode,'batch')
 error('ctocscreen:config:mode','Unknown mode.');
end
end
